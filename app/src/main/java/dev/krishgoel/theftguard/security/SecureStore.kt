package dev.krishgoel.theftguard.security

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import android.util.Base64
import dev.krishgoel.theftguard.Storage
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Encrypted key → value storage for emergency contacts and IMEIs (decision D2).
 *
 * AES-256-GCM with a key that lives in the Android Keystore (StrongBox chip if
 * available, else the TEE), like the PIN's HMAC key. Stored value:
 *     base64( IV (12 bytes) ‖ ciphertext ‖ GCM tag (16 bytes) )
 *
 * Why GCM? It encrypts AND authenticates. If anyone edits the stored bytes,
 * decryption fails instead of returning garbage.
 *
 * "AAD" (additional authenticated data): each value is bound to its field
 * name. Swapping the encrypted "contacts" blob into the "imei1" slot would
 * fail to decrypt, so values can't be shuffled around.
 *
 * The IV is generated by the Keystore for every write (never reused: reusing
 * a GCM IV with the same key is a classic, catastrophic crypto bug).
 */
object SecureStore {
    private const val ALIAS = "theftguard_data_aes_v1"
    private const val PROVIDER = "AndroidKeyStore"
    private const val PREFS = "secure_store"
    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val IV_BYTES = 12
    private const val TAG_BITS = 128

    fun put(ctx: Context, name: String, value: String?) {
        val prefs = Storage.prefs(ctx, PREFS)
        if (value == null) {
            prefs.edit().remove(name).commit()
            return
        }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        cipher.updateAAD(name.toByteArray(Charsets.UTF_8))
        val sealed = cipher.iv + cipher.doFinal(value.toByteArray(Charsets.UTF_8))
        prefs.edit().putString(name, Base64.encodeToString(sealed, Base64.NO_WRAP)).commit()
    }

    /** Null if missing, or if it can't be decrypted (tampered, or key unavailable). */
    fun get(ctx: Context, name: String): String? {
        val stored = Storage.prefs(ctx, PREFS).getString(name, null) ?: return null
        return try {
            val bytes = Base64.decode(stored, Base64.NO_WRAP)
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, bytes, 0, IV_BYTES))
            cipher.updateAAD(name.toByteArray(Charsets.UTF_8))
            String(cipher.doFinal(bytes, IV_BYTES, bytes.size - IV_BYTES), Charsets.UTF_8)
        } catch (e: Exception) {
            null
        }
    }

    @Synchronized
    private fun key(): SecretKey {
        val ks = KeyStore.getInstance(PROVIDER).apply { load(null) }
        (ks.getKey(ALIAS, null) as? SecretKey)?.let { return it }
        return try {
            generate(strongBox = true)
        } catch (e: StrongBoxUnavailableException) {
            generate(strongBox = false)
        }
    }

    private fun generate(strongBox: Boolean): SecretKey {
        val spec = KeyGenParameterSpec.Builder(
            ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setIsStrongBoxBacked(strongBox)
            // Not setUnlockedDeviceRequired: alerts must work on a locked phone.
            .build()
        return KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
            .apply { init(spec) }
            .generateKey()
    }
}
